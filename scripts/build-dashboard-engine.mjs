// =============================================================================
// Dashboard Render Engine build
// Bundles src/dashboard-engine into a single IIFE and copies the engine tokens
// stylesheet, placing both in the backend's generated assets directory. The
// backend loads these artifacts via readFileSync (no runtime esbuild needed).
//
//   npm run build:engine
// =============================================================================

import esbuild from 'esbuild';
import { copyFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const outDir = path.resolve(repoRoot, '../backend/services/de-dashboard/generated');

mkdirSync(outDir, { recursive: true });

await esbuild.build({
  entryPoints: [path.join(repoRoot, 'src/dashboard-engine/index.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  outfile: path.join(outDir, 'dashboard-runtime.bundle.js'),
  banner: {
    js: '// SW Dashboard Render Engine bundle — generated by sw-data-explorer (npm run build:engine). Do not edit.',
  },
  logLevel: 'info',
});

copyFileSync(
  path.join(repoRoot, 'src/dashboard-engine/tokens.css'),
  path.join(outDir, 'dashboard-runtime.tokens.css')
);

console.log(`[build:engine] wrote dashboard-runtime.bundle.js + dashboard-runtime.tokens.css -> ${outDir}`);